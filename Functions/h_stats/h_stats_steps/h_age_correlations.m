function h_age_correlations(T_subj, C, HC, ANALYSIS_TAG)
% H_AGE_CORRELATIONS  Age vs coherence correlations (one point per subject, and
% by condition), tables and figures. Runs when HC.analysis.run_age_correlations.

    %% ===================== AGE CORRELATIONS =====================

    runAgeCorrelations = ...
        isfield(HC.analysis, 'run_age_correlations') && ...
        HC.analysis.run_age_correlations;

    % Initialize outputs for robustness
    AGE_METRIC_TABLE = table();
    AGE_COND_TABLE   = table();

    if runAgeCorrelations

        % Common settings for both age-correlation blocks
        ageCorrMetrics = HC.analysis.age_corr_metrics;

        useCycleCorr = ...
            isfield(HC.analysis, 'include_cycle_count_in_correlations') && ...
            HC.analysis.include_cycle_count_in_correlations;

        if useCycleCorr
            corrTag = "partialcyclecorr";
        else
            corrTag = "simplecorr";
        end


        %% ===================== AGE VS COHERENCE METRICS:
        %                       ONE POINT PER SUBJECT =====================

        fprintf('\nRunning age-vs-coherence correlations: one point per subject...\n');

        agePeakDir = fullfile( ...
            HC.io.plots_dir, ...
            'age_metric_correlations_one_point_per_subject');

        if ~exist(agePeakDir, 'dir')
            mkdir(agePeakDir);
        end

        AGE_METRIC_ROWS = {};
        riAP = 0;

        for ip = 1:numel(HC.analysis.pairs_to_analyze)

            pairName = string(HC.analysis.pairs_to_analyze{ip});

            Tp = T_subj(T_subj.pair_name == pairName, :);

            if isempty(Tp)
                continue;
            end

            for im = 1:numel(ageCorrMetrics)

                dv = ageCorrMetrics{im};

                if ~ismember(dv, Tp.Properties.VariableNames)
                    continue;
                end

                % Keep rows with valid age and metric
                Tm = Tp( ...
                    ~isnan(Tp.AgeMonths) & ...
                    ~isnan(Tp.(dv)), :);

                % Optional DV-specific cycle-count covariate
                [Tm, useCycleCorrThisMetric, ~] = ...
                    add_log_cycle_covariate_for_dv( ...
                        Tm, ...
                        dv, ...
                        useCycleCorr);

                if height(Tm) < 5
                    continue;
                end

                % ---------------------------------------------------------
                % Collapse to one point per subject
                % Conditions are averaged here
                % ---------------------------------------------------------
                groupVars = { ...
                    'subject', ...
                    'age_group', ...
                    'AgeMonths', ...
                    'AgeYears'};

                G = findgroups(Tm(:, groupVars));

                T_age = unique(Tm(:, groupVars), 'rows');

                T_age.metric_value = splitapply( ...
                    @(x) mean(x, 'omitnan'), ...
                    Tm.(dv), ...
                    G);

                T_age.n_observations_collapsed = splitapply( ...
                    @(x) sum(~isnan(x)), ...
                    Tm.(dv), ...
                    G);

                % Keep cycle-count covariate after collapse if available
                if ismember('log_n_cycles', Tm.Properties.VariableNames)

                    T_age.log_n_cycles = splitapply( ...
                        @(x) mean(x, 'omitnan'), ...
                        Tm.log_n_cycles, ...
                        G);
                end

                % Remove invalid observations
                T_age = T_age( ...
                    ~isnan(T_age.metric_value) & ...
                    ~isnan(T_age.AgeYears), :);

                if height(T_age) < 5
                    continue;
                end

                % ---------------------------------------------------------
                % Correlations
                % ---------------------------------------------------------
                ageYears = T_age.AgeYears;
                y = T_age.metric_value;

                [rPearson, pPearson] = corr( ...
                    ageYears, ...
                    y, ...
                    'Type', 'Pearson', ...
                    'Rows', 'complete');

                [rhoSpearman, pSpearman] = corr( ...
                    ageYears, ...
                    y, ...
                    'Type', 'Spearman', ...
                    'Rows', 'complete');

                % ---------------------------------------------------------
                % Optional partial correlation controlling for cycle count
                % ---------------------------------------------------------
                rPartialCycle = NaN;
                pPartialCycle = NaN;
                nPartialCycle = 0;

                if useCycleCorrThisMetric && ...
                        ismember('log_n_cycles', T_age.Properties.VariableNames)

                    zCycle = T_age.log_n_cycles;

                    validPartial = ...
                        isfinite(ageYears) & ...
                        isfinite(y) & ...
                        isfinite(zCycle);

                    nPartialCycle = sum(validPartial);

                    if nPartialCycle >= 5

                        [rPartialCycle, pPartialCycle] = partialcorr( ...
                            ageYears(validPartial), ...
                            y(validPartial), ...
                            zCycle(validPartial), ...
                            'Rows', 'complete');
                    end
                end

                % ---------------------------------------------------------
                % Save result row
                % ---------------------------------------------------------
                riAP = riAP + 1;

                AGE_METRIC_ROWS(riAP,:) = { ...
                    pairName, ...
                    string(dv), ...
                    height(T_age), ...
                    rPearson, ...
                    pPearson, ...
                    rhoSpearman, ...
                    pSpearman, ...
                    rPartialCycle, ...
                    pPartialCycle, ...
                    nPartialCycle, ...
                    useCycleCorrThisMetric ...
                    };

                % ---------------------------------------------------------
                % Plot
                % ---------------------------------------------------------
                fig = figure( ...
                    'Visible', HC.plot.visible, ...
                    'Color', 'w', ...
                    'Position', [100 100 650 520]);

                hold on;

                ageLevels = categories(removecats(T_age.age_group));

                for ia = 1:numel(ageLevels)

                    ag = ageLevels{ia};
                    idx = T_age.age_group == ag;

                    col = get_age_color(ag, C);

                    scatter( ...
                        ageYears(idx), ...
                        y(idx), ...
                        50, ...
                        'filled', ...
                        'MarkerFaceColor', col, ...
                        'MarkerEdgeColor', col, ...
                        'DisplayName', char(ag));
                end

                % Simple linear fit for visualization only
                mdl = fitlm(ageYears, y);

                xfit = linspace( ...
                    min(ageYears), ...
                    max(ageYears), ...
                    100)';

                yfit = predict(mdl, xfit);

                plot( ...
                    xfit, ...
                    yfit, ...
                    'k-', ...
                    'LineWidth', 1.5, ...
                    'HandleVisibility', 'off');

                xlabel('Age (years)');
                ylabel(strrep(dv, '_', ' '));

                title( ...
                    sprintf( ...
                        '%s | %s | %s %s | 1 point/subject', ...
                        pairName, ...
                        strrep(dv, '_', ' '), ...
                        string(HC.analysis.coherence_source), ...
                        get_metric_scope_label(HC.analysis.metric_scope)), ...
                    'Interpreter', 'none');

                if useCycleCorrThisMetric && isfinite(rPartialCycle)

                    txt = sprintf( ...
                        ['r = %.2f, p = %.3g, n = %d\n' ...
                        'partial r = %.2f, p = %.3g'], ...
                        rPearson, ...
                        pPearson, ...
                        height(T_age), ...
                        rPartialCycle, ...
                        pPartialCycle);

                else

                    txt = sprintf( ...
                        'r = %.2f, p = %.3g, n = %d', ...
                        rPearson, ...
                        pPearson, ...
                        height(T_age));
                end

                text( ...
                    0.05, ...
                    0.95, ...
                    txt, ...
                    'Units', 'normalized', ...
                    'Parent', gca, ...
                    'HorizontalAlignment', 'left', ...
                    'VerticalAlignment', 'top', ...
                    'FontSize', 11, ...
                    'FontWeight', 'bold', ...
                    'BackgroundColor', 'w', ...
                    'Margin', 3);

                lgd = legend( ...
                    'Location', 'southoutside', ...
                    'Orientation', 'horizontal', ...
                    'Interpreter', 'none');

                lgd.Box = 'off';

                grid on;

                apply_correlation_ylim(gca, HC, dv);

                if exist('ANALYSIS_TAG', 'var')

                    outName = sprintf( ...
                        'AGE_VS_%s__%s__%s__%s__ONE_POINT_PER_SUBJECT.png', ...
                        dv, ...
                        pairName, ...
                        ANALYSIS_TAG, ...
                        corrTag);

                else

                    outName = sprintf( ...
                        'AGE_VS_%s__%s__%s__%s__%s__ONE_POINT_PER_SUBJECT.png', ...
                        dv, ...
                        pairName, ...
                        lower(char(string(HC.analysis.metric_scope))), ...
                        lower(char(string(HC.analysis.coherence_source))), ...
                        corrTag);
                end

                saveas(fig, fullfile(agePeakDir, outName));
                close(fig);

            end
        end

        % ---------------------------------------------------------
        % Save one-point-per-subject correlation table
        % ---------------------------------------------------------
        if ~isempty(AGE_METRIC_ROWS)

            AGE_METRIC_TABLE = cell2table( ...
                AGE_METRIC_ROWS, ...
                'VariableNames', { ...
                    'pair_name', ...
                    'metric', ...
                    'n_subjects', ...
                    'r_pearson', ...
                    'p_pearson', ...
                    'rho_spearman', ...
                    'p_spearman', ...
                    'r_partial_log_n_cycles', ...
                    'p_partial_log_n_cycles', ...
                    'n_partial_log_n_cycles', ...
                    'cycle_count_control_requested' ...
                    });

            if exist('ANALYSIS_TAG', 'var')

                writetable( ...
                    AGE_METRIC_TABLE, ...
                    fullfile( ...
                        HC.io.tables_dir, ...
                        sprintf( ...
                            'AGE_METRIC_CORRELATIONS_ONE_POINT_PER_SUBJECT__%s__%s.csv', ...
                            ANALYSIS_TAG, ...
                            corrTag)));
            end

            % Optional latest-copy file
            writetable( ...
                AGE_METRIC_TABLE, ...
                fullfile( ...
                    HC.io.tables_dir, ...
                    'AGE_METRIC_CORRELATIONS_ONE_POINT_PER_SUBJECT.csv'));

            disp(AGE_METRIC_TABLE);

        else

            warning('No age-metric correlations were computed.');
        end


        %% ===================== AGE VS METRIC BY CONDITION TRIPLETS =====================

        fprintf('\nRunning age-vs-coherence by-condition triplets...\n');

        ageCondDir = fullfile( ...
            HC.io.plots_dir, ...
            'age_metric_correlations_by_condition_triplets');

        if ~exist(ageCondDir, 'dir')
            mkdir(ageCondDir);
        end

        AGE_COND_ROWS = {};
        riAC = 0;

        condOrder = cellstr(C.plotting.condition_order);

        for ip = 1:numel(HC.analysis.pairs_to_analyze)

            pairName = string(HC.analysis.pairs_to_analyze{ip});

            Tp_pair = T_subj(T_subj.pair_name == pairName, :);

            if isempty(Tp_pair)
                continue;
            end

            for im = 1:numel(ageCorrMetrics)

                dv = ageCorrMetrics{im};

                if ~ismember(dv, Tp_pair.Properties.VariableNames)
                    continue;
                end

                fig = figure( ...
                    'Visible', HC.plot.visible, ...
                    'Color', 'w', ...
                    'Position', [100 100 1650 600]);

                tl = tiledlayout( ...
                    fig, ...
                    1, ...
                    3, ...
                    'TileSpacing', 'compact', ...
                    'Padding', 'compact');

                tl.OuterPosition = [0.04 0.08 0.94 0.78];

                axAll = gobjects(1, numel(condOrder));

                for ic = 1:numel(condOrder)

                    condName = condOrder{ic};

                    ax = nexttile(tl, ic);
                    axAll(ic) = ax;

                    hold(ax, 'on');

                    Tp = Tp_pair(Tp_pair.condition == condName, :);

                    Tm = Tp( ...
                        ~isnan(Tp.AgeMonths) & ...
                        ~isnan(Tp.(dv)), :);

                    % Optional DV-specific cycle-count covariate
                    [Tm, useCycleCorrThisMetric, ~] = ...
                        add_log_cycle_covariate_for_dv( ...
                            Tm, ...
                            dv, ...
                            useCycleCorr);

                    if isempty(Tm)

                        title(ax, condName, 'Interpreter', 'none');
                        axis(ax, 'off');

                        continue;
                    end

                    % -----------------------------------------------------
                    % Collapse to one row per subject WITHIN condition
                    % -----------------------------------------------------
                    groupVars = { ...
                        'subject', ...
                        'age_group', ...
                        'AgeMonths', ...
                        'AgeYears'};

                    G = findgroups(Tm(:, groupVars));

                    T_age = unique(Tm(:, groupVars), 'rows');

                    T_age.metric_value = splitapply( ...
                        @(x) mean(x, 'omitnan'), ...
                        Tm.(dv), ...
                        G);

                    T_age.n_observations_collapsed = splitapply( ...
                        @(x) sum(~isnan(x)), ...
                        Tm.(dv), ...
                        G);

                    if ismember('log_n_cycles', Tm.Properties.VariableNames)

                        T_age.log_n_cycles = splitapply( ...
                            @(x) mean(x, 'omitnan'), ...
                            Tm.log_n_cycles, ...
                            G);
                    end

                    T_age = T_age( ...
                        ~isnan(T_age.metric_value) & ...
                        ~isnan(T_age.AgeYears), :);

                    if height(T_age) < 5

                        title( ...
                            ax, ...
                            sprintf('%s | n=%d', ...
                                condName, ...
                                height(T_age)), ...
                            'Interpreter', 'none');

                        axis(ax, 'off');

                        continue;
                    end

                    % -----------------------------------------------------
                    % Correlations
                    % -----------------------------------------------------
                    ageYears = T_age.AgeYears;
                    y = T_age.metric_value;

                    [rPearson, pPearson] = corr( ...
                        ageYears, ...
                        y, ...
                        'Type', 'Pearson', ...
                        'Rows', 'complete');

                    [rhoSpearman, pSpearman] = corr( ...
                        ageYears, ...
                        y, ...
                        'Type', 'Spearman', ...
                        'Rows', 'complete');

                    % -----------------------------------------------------
                    % Optional partial correlation controlling cycle count
                    % -----------------------------------------------------
                    rPartialCycle = NaN;
                    pPartialCycle = NaN;
                    nPartialCycle = 0;

                    if useCycleCorrThisMetric && ...
                            ismember('log_n_cycles', T_age.Properties.VariableNames)

                        zCycle = T_age.log_n_cycles;

                        validPartial = ...
                            isfinite(ageYears) & ...
                            isfinite(y) & ...
                            isfinite(zCycle);

                        nPartialCycle = sum(validPartial);

                        if nPartialCycle >= 5

                            [rPartialCycle, pPartialCycle] = partialcorr( ...
                                ageYears(validPartial), ...
                                y(validPartial), ...
                                zCycle(validPartial), ...
                                'Rows', 'complete');
                        end
                    end

                    % -----------------------------------------------------
                    % Save result row
                    % -----------------------------------------------------
                    riAC = riAC + 1;

                    AGE_COND_ROWS(riAC,:) = { ...
                        pairName, ...
                        string(dv), ...
                        string(condName), ...
                        height(T_age), ...
                        rPearson, ...
                        pPearson, ...
                        rhoSpearman, ...
                        pSpearman, ...
                        rPartialCycle, ...
                        pPartialCycle, ...
                        nPartialCycle, ...
                        useCycleCorrThisMetric ...
                        };

                    % -----------------------------------------------------
                    % Plot
                    % -----------------------------------------------------
                    ageLevels = categories(removecats(T_age.age_group));

                    for ia = 1:numel(ageLevels)

                        ag = ageLevels{ia};

                        idx = T_age.age_group == ag;

                        col = get_age_color(ag, C);

                        scatter( ...
                            ax, ...
                            ageYears(idx), ...
                            y(idx), ...
                            50, ...
                            'filled', ...
                            'MarkerFaceColor', col, ...
                            'MarkerEdgeColor', col, ...
                            'DisplayName', char(ag));
                    end

                    mdl = fitlm(ageYears, y);

                    xfit = linspace( ...
                        min(ageYears), ...
                        max(ageYears), ...
                        100)';

                    yfit = predict(mdl, xfit);

                    plot( ...
                        ax, ...
                        xfit, ...
                        yfit, ...
                        'k-', ...
                        'LineWidth', 1.5, ...
                        'HandleVisibility', 'off');

                    xlabel(ax, 'Age (years)');
                    ylabel(ax, strrep(dv, '_', ' '));

                    title( ...
                        ax, ...
                        condName, ...
                        'Interpreter', 'none');

                    if useCycleCorrThisMetric && isfinite(rPartialCycle)

                        txt = sprintf( ...
                            ['r = %.2f, p = %.3g, n = %d\n' ...
                            'partial r = %.2f, p = %.3g'], ...
                            rPearson, ...
                            pPearson, ...
                            height(T_age), ...
                            rPartialCycle, ...
                            pPartialCycle);

                    else

                        txt = sprintf( ...
                            'r = %.2f, p = %.3g, n = %d', ...
                            rPearson, ...
                            pPearson, ...
                            height(T_age));
                    end

                    text( ...
                        ax, ...
                        0.05, ...
                        0.95, ...
                        txt, ...
                        'Units', 'normalized', ...
                        'HorizontalAlignment', 'left', ...
                        'VerticalAlignment', 'top', ...
                        'FontSize', 10, ...
                        'FontWeight', 'bold', ...
                        'BackgroundColor', 'w', ...
                        'Margin', 3);

                    grid(ax, 'on');

                end

                % ---------------------------------------------------------
                % Shared y limits
                % ---------------------------------------------------------
                validAx = axAll(isgraphics(axAll));

                if isfield(HC, 'plot') && ...
                        isfield(HC.plot, 'correlation_use_fixed_ylim') && ...
                        HC.plot.correlation_use_fixed_ylim

                    for iax = 1:numel(validAx)

                        apply_correlation_ylim( ...
                            validAx(iax), ...
                            HC, ...
                            dv);
                    end

                else

                    allY = [];

                    for iax = 1:numel(validAx)

                        yl = ylim(validAx(iax));

                        allY = [allY yl]; %#ok<AGROW>
                    end

                    if ~isempty(allY)

                        yMin = min(allY);
                        yMax = max(allY);

                        yRange = yMax - yMin;

                        if yRange <= 0
                            yRange = 0.1;
                        end

                        sharedYLims = [ ...
                            yMin - 0.03*yRange, ...
                            yMax + 0.08*yRange];

                        for iax = 1:numel(validAx)

                            ylim( ...
                                validAx(iax), ...
                                sharedYLims);
                        end
                    end
                end

                sgtitle( ...
                    fig, ...
                    sprintf( ...
                        '%s | %s | %s %s | one point/subject/condition', ...
                        pairName, ...
                        strrep(dv, '_', ' '), ...
                        string(HC.analysis.coherence_source), ...
                        get_metric_scope_label(HC.analysis.metric_scope)), ...
                    'Interpreter', 'none');

                % ---------------------------------------------------------
                % Shared legend
                % ---------------------------------------------------------
                allAxes = findall(fig, 'Type', 'axes');

                hScat = findobj( ...
                    allAxes, ...
                    'Type', 'Scatter');

                if ~isempty(hScat)

                    labels = get(hScat, 'DisplayName');

                    if ischar(labels)
                        labels = {labels};
                    end

                    valid = ~cellfun(@isempty, labels);

                    hScat = hScat(valid);
                    labels = labels(valid);

                    [uniqueLabels, ia] = unique( ...
                        labels, ...
                        'stable');

                    hScat = hScat(ia);

                    legendAx = axes( ...
                        fig, ...
                        'Position', [0.70 0.91 0.27 0.06], ...
                        'Visible', 'off');

                    lgd = legend( ...
                        legendAx, ...
                        hScat, ...
                        uniqueLabels, ...
                        'Orientation', 'horizontal', ...
                        'Interpreter', 'none');

                    lgd.Box = 'off';
                    lgd.FontSize = 12;
                    lgd.ItemTokenSize = [18 12];
                    lgd.Units = 'normalized';
                    lgd.Position = [0.70 0.91 0.27 0.06];
                end

                % ---------------------------------------------------------
                % Save figure
                % ---------------------------------------------------------
                if exist('ANALYSIS_TAG', 'var')

                    outName = sprintf( ...
                        'AGE_VS_%s__%s__BY_CONDITION_TRIPLET__%s__%s.png', ...
                        dv, ...
                        pairName, ...
                        ANALYSIS_TAG, ...
                        corrTag);

                else

                    outName = sprintf( ...
                        'AGE_VS_%s__%s__BY_CONDITION_TRIPLET__%s__%s_%s.png', ...
                        dv, ...
                        pairName, ...
                        lower(char(string(HC.analysis.metric_scope))), ...
                        lower(char(string(HC.analysis.coherence_source))), ...
                        corrTag);
                end

                saveas( ...
                    fig, ...
                    fullfile(ageCondDir, outName));

                close(fig);

            end
        end

        % ---------------------------------------------------------
        % Save by-condition correlation table
        % ---------------------------------------------------------
        if ~isempty(AGE_COND_ROWS)

            AGE_COND_TABLE = cell2table( ...
                AGE_COND_ROWS, ...
                'VariableNames', { ...
                    'pair_name', ...
                    'metric', ...
                    'condition', ...
                    'n_subjects', ...
                    'r_pearson', ...
                    'p_pearson', ...
                    'rho_spearman', ...
                    'p_spearman', ...
                    'r_partial_log_n_cycles', ...
                    'p_partial_log_n_cycles', ...
                    'n_partial_log_n_cycles', ...
                    'cycle_count_control_requested' ...
                    });

            if exist('ANALYSIS_TAG', 'var')

                writetable( ...
                    AGE_COND_TABLE, ...
                    fullfile( ...
                        HC.io.tables_dir, ...
                        sprintf( ...
                            'AGE_METRIC_CORRELATIONS_BY_CONDITION__%s__%s.csv', ...
                            ANALYSIS_TAG, ...
                            corrTag)));
            end

            % Optional latest-copy file
            writetable( ...
                AGE_COND_TABLE, ...
                fullfile( ...
                    HC.io.tables_dir, ...
                    'AGE_METRIC_CORRELATIONS_BY_CONDITION.csv'));

            disp(AGE_COND_TABLE);

        else

            warning('No by-condition age-metric correlations were computed.');
        end

    else

        fprintf('\nAge correlations are disabled.\n');

    end
end
