function log_rows = append_log(log_rows, severity, event_type, subj, cond, trial, leg, mus, file_name, file_path, reason, details)

    ts = char(datetime('now','Format','yyyy-MM-dd HH:mm:ss'));

    log_rows(end+1,:) = { ...
        ts, ...
        char(string(severity)), ...
        char(string(event_type)), ...
        char(string(subj)), ...
        char(string(cond)), ...
        char(string(trial)), ...
        char(string(leg)), ...
        char(string(mus)), ...
        char(string(file_name)), ...
        char(string(file_path)), ...
        char(string(reason)), ...
        char(string(details)) ...
    };
end