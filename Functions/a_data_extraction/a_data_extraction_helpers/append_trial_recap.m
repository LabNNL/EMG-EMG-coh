function trial_rows = append_trial_recap(trial_rows, subjID, cond, trial_id, expected_file, actual_file_used, file_status, left_hs_count, right_hs_count, left_muscles_with_data, right_muscles_with_data, main_issue)

    if isempty(actual_file_used)
        actual_file_used = "";
    end
    if isempty(file_status)
        file_status = "";
    end
    if isempty(main_issue)
        main_issue = "";
    end

    trial_rows(end+1,:) = { ...
        char(string(subjID)), ...
        char(string(cond)), ...
        char(string(trial_id)), ...
        char(string(expected_file)), ...
        char(string(actual_file_used)), ...
        char(string(file_status)), ...
        left_hs_count, ...
        right_hs_count, ...
        left_muscles_with_data, ...
        right_muscles_with_data, ...
        char(string(main_issue)) ...
    };
end