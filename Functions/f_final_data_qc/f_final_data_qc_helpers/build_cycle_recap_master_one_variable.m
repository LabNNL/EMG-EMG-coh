
function Tout = build_cycle_recap_master_one_variable(T, valueVar, inclusionMode)

    if isempty(T) || ~ismember(valueVar, T.Properties.VariableNames)
        Tout = table();
        return;
    end

    % Always pair-specific. ALL is added for age/condition when collapsed.
    groupSets = { ...
        {'pair_name'}, ...
        {'pair_name','age_group'}, ...
        {'pair_name','condition'}, ...
        {'pair_name','age_group','condition'}};

    levelNames = { ...
        "pair_all_age_all_condition", ...
        "pair_age_all_condition", ...
        "pair_all_age_condition", ...
        "pair_age_condition"};

    rows = {};

    for iG = 1:numel(groupSets)
        groupVars = groupSets{iG};
        levelName = levelNames{iG};

        G = findgroups(T(:, groupVars));
        keys = unique(T(:, groupVars), 'rows');

        localRows = {};

        for k = 1:max(G)
            idx = G == k;
            x = T.(valueVar)(idx);
            x = x(:);
            x = x(~isnan(x));

            localRows(k,:) = [ ...
                table2cell(keys(k,:)), ...
                { ...
                numel(x), ...
                mean(x, 'omitnan'), ...
                median(x, 'omitnan'), ...
                std(x, 'omitnan'), ...
                min(x), ...
                prctile(x, 25), ...
                prctile(x, 75), ...
                max(x), ...
                sum(x < 10), ...
                100 * mean(x < 10, 'omitnan'), ...
                sum(x >= 10), ...
                100 * mean(x >= 10, 'omitnan') ...
                } ...
                ]; %#ok<AGROW>
        end

        Tlocal = cell2table(localRows, 'VariableNames', [groupVars, { ...
            'n_rows', ...
            'mean_value', ...
            'median_value', ...
            'std_value', ...
            'min_value', ...
            'q25_value', ...
            'q75_value', ...
            'max_value', ...
            'n_below_10', ...
            'percent_below_10', ...
            'n_at_or_above_10', ...
            'percent_at_or_above_10'}]);

        if ~ismember('age_group', Tlocal.Properties.VariableNames)
            Tlocal.age_group = repmat("ALL", height(Tlocal), 1);
        end

        if ~ismember('condition', Tlocal.Properties.VariableNames)
            Tlocal.condition = repmat("ALL", height(Tlocal), 1);
        end

        Tlocal.inclusion_mode = repmat(string(inclusionMode), height(Tlocal), 1);
        Tlocal.value_variable = repmat(string(valueVar), height(Tlocal), 1);
        Tlocal.recap_level = repmat(string(levelName), height(Tlocal), 1);

        Tlocal = movevars(Tlocal, ...
            {'inclusion_mode','value_variable','recap_level','pair_name','age_group','condition'}, ...
            'Before', 1);

        rows{end+1,1} = Tlocal; %#ok<AGROW>
    end

    Tout = vertcat_fill_missing(rows{:});
end