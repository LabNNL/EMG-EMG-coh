function Tout = build_master_cycle_distribution_by_pair_band(T, bandLabel, includeVar, cycleVar)

    if isempty(T) || ~ismember(includeVar, T.Properties.VariableNames) || ~ismember(cycleVar, T.Properties.VariableNames)
        Tout = table();
        return;
    end

    T = T(T.(includeVar) == true, :);

    if isempty(T)
        Tout = table();
        return;
    end

    groupSets = { ...
        {'pair_name'}, ...
        {'pair_name','age_group'}, ...
        {'pair_name','condition'}, ...
        {'pair_name','age_group','condition'}};

    levelNames = { ...
        "pair_all_age_all_condition", ...
        "pair_age_all_condition", ...
        "pair_all_age_condition", ...
        "pair_age_condition"};

    rows = {};

    for iG = 1:numel(groupSets)
        groupVars = groupSets{iG};
        levelName = levelNames{iG};

        G = findgroups(T(:, groupVars));
        keys = unique(T(:, groupVars), 'rows');

        localRows = {};

        for k = 1:max(G)
            idx = G == k;
            x = T.(cycleVar)(idx);
            x = x(:);
            x = x(~isnan(x));

            nParticipants = numel(unique(string(T.subject(idx))));

            localRows(k,:) = [ ...
                table2cell(keys(k,:)), ...
                { ...
                nParticipants, ...
                numel(x), ...
                mean(x, 'omitnan'), ...
                median(x, 'omitnan'), ...
                std(x, 'omitnan'), ...
                min(x), ...
                prctile(x, 25), ...
                prctile(x, 75), ...
                max(x), ...
                100 * mean(x < 10, 'omitnan'), ...
                100 * mean(x >= 10, 'omitnan') ...
                } ...
                ]; %#ok<AGROW>
        end

        Tlocal = cell2table(localRows, 'VariableNames', [groupVars, { ...
            'n_participants', ...
            'n_signals', ...
            'mean_cycles', ...
            'median_cycles', ...
            'std_cycles', ...
            'min_cycles', ...
            'q25_cycles', ...
            'q75_cycles', ...
            'max_cycles', ...
            'percent_below_10_cycles', ...
            'percent_at_or_above_10_cycles'}]);

        if ~ismember('age_group', Tlocal.Properties.VariableNames)
            Tlocal.age_group = repmat("ALL", height(Tlocal), 1);
        end

        if ~ismember('condition', Tlocal.Properties.VariableNames)
            Tlocal.condition = repmat("ALL", height(Tlocal), 1);
        end

        Tlocal.band = repmat(string(bandLabel), height(Tlocal), 1);
        Tlocal.recap_family = repmat("cycle_distribution", height(Tlocal), 1);
        Tlocal.recap_level = repmat(levelName, height(Tlocal), 1);
        Tlocal.cycle_variable = repmat(string(cycleVar), height(Tlocal), 1);

        Tlocal = movevars(Tlocal, ...
            {'band','recap_family','recap_level','cycle_variable','pair_name','age_group','condition'}, ...
            'Before', 1);

        rows{end+1,1} = Tlocal; %#ok<AGROW>
    end

    Tout = vertcat_fill_missing(rows{:});
end