function Tout = build_master_participant_recap_by_pair_band(T, bandLabel)

    if isempty(T)
        Tout = table();
        return;
    end

    ids = unique(T(:, {'subject','age_group','pair_name'}));
    rows = {};

    for i = 1:height(ids)

        idx = string(T.subject) == string(ids.subject(i)) & ...
              string(T.pair_name) == string(ids.pair_name(i));

        Ti = T(idx,:);

        rows(end+1,:) = { ...
            string(ids.subject(i)), ...
            string(ids.age_group(i)), ...
            string(ids.pair_name(i)), ...
            numel(unique(string(Ti.condition))), ...
            numel(unique(string(Ti.leg))), ...
            height(Ti), ...
            strjoin(unique(string(Ti.condition)), ","), ...
            strjoin(unique(string(Ti.leg)), ",") ...
            }; %#ok<AGROW>
    end

    Tout = cell2table(rows, 'VariableNames', { ...
        'subject','age_group','pair_name', ...
        'n_unique_conditions','n_unique_legs','n_signal_rows', ...
        'conditions_list','legs_list'});

    Tout.condition = repmat("ALL", height(Tout), 1);
    Tout.band = repmat(string(bandLabel), height(Tout), 1);
    Tout.recap_family = repmat("participant", height(Tout), 1);
    Tout.recap_level = repmat("participant_pair", height(Tout), 1);

    Tout = movevars(Tout, ...
        {'band','recap_family','recap_level','pair_name','age_group','condition'}, ...
        'Before', 1);
end
